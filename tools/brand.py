# ---------- the curtain ----------
def _noise(n, scale, rng):
    """Smooth 1-D value noise in -1..1 with features about `scale` samples apart."""
    k = max(2, int(n / scale) + 3)
    pts = rng.uniform(-1, 1, k)
    xs = np.linspace(0, k - 1, n)
    i = np.floor(xs).astype(int)
    t = xs - i
    t = t * t * (3 - 2 * t)
    return pts[i] * (1 - t) + pts[np.minimum(i + 1, k - 1)] * t


def curtain(w, h, *, seed=11, fold=104.0, light=(0.5, -0.35), spread=0.62, gather=0.35, grain=0.018, vignette=(0.42, 0.22),
            deep=(0.035, 0.012, 0.028), body=(0.38, 0.06, 0.19), sheen=(0.88, 0.40, 0.55), warm=(1.0, 0.72, 0.42)):
    """A plum velvet curtain lit from above, as a float RGB array (h, w, 3) in 0..1.

    fold: fold width in px at the top; gather: how much wider the folds get toward the floor; light: the stage
    light's position (x as a fraction of the width, y as a fraction of the height, negative = above the frame);
    vignette: (centre height as a fraction, how dark the corners get)."""
    rng = np.random.default_rng(seed)
    y = np.linspace(0, 1, h)[:, None]
    x = np.arange(w)[None, :].astype(float)
    # folds laid out along u (the curtain rail), fanning out a little toward the floor
    U = w * 2
    phase_u = np.cumsum(2 * np.pi / (fold * (1 + 0.35 * _noise(U, U / 14, rng))))
    cx = w * light[0]
    sway = 5 * _noise(h, h / 2, rng)[:, None] * y
    u = np.clip(w + (x - cx) / (1 - gather / 2 + gather * y) + (cx - w / 2) + sway, 0, U - 1)
    phase = np.interp(u, np.arange(U), phase_u)
    amp = np.interp(u, np.arange(U), 0.75 + 0.25 * _noise(U, U / 22, rng))
    s = np.sin(phase)
    z = amp * np.sign(s) * np.abs(s) ** 0.8          # rounder crests, sharper valleys than a sine
    dz = np.gradient(z, axis=1) * (fold / (2 * np.pi)) * 1.6
    n = np.sqrt(dz ** 2 + 1)
    nx, nz = -dz / n, 1 / n
    dxl = (light[0] * w - x) / w
    dl = np.sqrt(dxl ** 2 + 0.25)
    diffuse = np.clip(nx * dxl / dl + nz * 0.5 / dl, 0, 1) ** 1.5
    # velvet: the pile catches light where the cloth turns away from you, so fold edges glow
    edge = (1 - nz) ** 1.2 * np.clip(0.4 + nx * np.sign(dxl + 1e-9) * 0.9, 0, 1.3)
    pool = np.exp(-(((x / w - light[0]) / spread) ** 2 + (y - light[1]) ** 2) * 1.5)
    shade = 0.25 + 0.75 * ((z + 1) / 2) ** 0.7
    pile = 1 + 0.07 * _noise(w, 1.6, rng)[None, :] + 0.025 * rng.standard_normal((h, w))
    lit = (pool * shade * pile)[..., None] * (np.array(body) * (0.25 + diffuse[..., None] * 1.1)
                                              + np.array(sheen) * edge[..., None] * 0.55)
    lit += (pool ** 3 * edge)[..., None] * 0.12 * np.array(warm)
    img = np.array(deep) * (0.6 + 0.4 * shade[..., None]) + lit
    img = img / (1 + img * 0.6)                       # a soft shoulder instead of clipped highlights
    if grain:
        img += grain * rng.standard_normal((h, w, 1)) * (0.35 + img.mean(axis=2, keepdims=True))
    yy, xx = np.mgrid[0:h, 0:w]
    vig = np.clip(1 - (((xx - w / 2) / (w * 0.62)) ** 2 + ((yy - h * vignette[0]) / (h * 0.85)) ** 2), 0, 1) ** 0.9
    return np.clip(img * (vignette[1] + (1 - vignette[1]) * vig[..., None]), 0, 1)


