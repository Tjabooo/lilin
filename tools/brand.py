def _place(box, x, y, h, anchor):
    s = h / box[1]
    w = box[0] * s
    if anchor == "center":
        x -= w / 2
    return f"translate({x:.2f} {y:.2f}) scale({s:.5f})", w, s


def _mark(d, bulbs, box, x, y, h, *, lit, letters, bulb, anchor, pool=True):
    tf, w, s = _place(box, x, y, h, anchor)
    out = []
    if lit and pool:
        out += [f'<circle cx="{cx}" cy="{cy}" r="{r * 8:.1f}" fill="url(#lb-pool)"/>' for cx, cy, r in bulbs]
    out.append(f'<path d="{d}" fill="{letters or ("url(#lb-paper)" if lit else PAPER)}"/>')
    if lit:
        out += [f'<circle cx="{cx}" cy="{cy}" r="{r * 2.7:.1f}" fill="url(#lb-halo)"/>' for cx, cy, r in bulbs]
        out += [f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="url(#lb-core)"/>' for cx, cy, r in bulbs]
    else:
        out += [f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="{bulb}"/>' for cx, cy, r in bulbs]
    return f'<g transform="{tf}">{"".join(out)}</g>', w


def wordmark(x, y, h, *, lit=False, letters=None, bulb=BULB, anchor="left", pool=True):
    """The wordmark with its top-left (or top-centre) at x, y and height h (l top to baseline). Returns (svg, width).
    lit: the bulbs glow (pool: and throw a faint warm light around them); letters/bulb: flat colours otherwise."""
    return _mark(WORDMARK_D, WORDMARK_BULBS, WORDMARK_BOX, x, y, h, lit=lit, letters=letters, bulb=bulb, anchor=anchor, pool=pool)


def monogram(x, y, h, *, lit=False, letters=None, bulb=BULB, anchor="center", pool=True):
    """The "li" monogram, like wordmark() but centred on x by default."""
