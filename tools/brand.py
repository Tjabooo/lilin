def rasterize(svg, w, h):
    """SVG text to a Pillow RGBA image of w x h (rsvg-convert)."""
    png = subprocess.run(["rsvg-convert", "-w", str(w), "-h", str(h)], input=svg.encode(), capture_output=True, check=True).stdout
    return Image.open(io.BytesIO(png)).convert("RGBA")


def save(img, path, *, grain=0.0, seed=3, opaque=False):
    """Writes a PNG; grain adds a whisper of film grain (opaque pictures only)."""
    if grain:
        a = np.asarray(img.convert("RGB")).astype(float) / 255
        rng = np.random.default_rng(seed)
        a = a + grain * rng.standard_normal(a.shape[:2])[..., None] * (0.25 + a.mean(axis=2, keepdims=True))
        img = Image.fromarray((np.clip(a, 0, 1) * 255 + 0.5).astype("uint8"))
    elif opaque:
        img = img.convert("RGB")
    if path.endswith(".jpg"):  # photographic pictures (the curtain): a fraction of the PNG's size, no visible loss
        img.convert("RGB").save(path, quality=88, subsampling=0, optimize=True, progressive=True)
    else:
        img.save(path, optimize=True)
